import random
from pathlib import Path

characters = [
    ("تفاحة", "الفراولة"),
    ("موزة", "الليمونة"),
    ("قطة صغيرة", "كلب شقي"),
    ("ولد ذكي", "صاحبه"),
    ("أرنب", "ثعلب"),
]

problems = [
    "اكتشف سرًا غريبًا في منتصف الليل",
    "خسر أهم مسابقة في حياته",
    "اكتشف أن أقرب شخص إليه كان بيخبي عنه الحقيقة",
    "وجد صندوقًا غامضًا أمام بيته",
    "ساعد شخصًا غريبًا، لكنه ندم على قراره",
]

twists = [
    "لكن المفاجأة إن الحقيقة كانت عكس كل توقعاته!",
    "وفجأة ظهر شخص غيّر كل الأحداث!",
    "لكن اللي حصل في النهاية محدش كان يتوقعه!",
    "وبعد ما عرف الحقيقة، قرر ياخد قرارًا غيّر حياته!",
    "وفي اللحظة الأخيرة اكتشف سرًا أكبر بكتير!",
]

first, second = random.choice(characters)
problem = random.choice(problems)
twist = random.choice(twists)

story = f"""
عنوان القصة: {first} و{second}

المشهد الأول:
كان يا ما كان، {first} كان عايش حياته بشكل طبيعي.

المشهد الثاني:
في يوم من الأيام، {second} ظهر في حياته،
وحصلت مشكلة محدش كان متوقعها.

المشهد الثالث:
{first} {problem}.

المشهد الرابع:
{twist}

النهاية:
يتبع... لو عايز تعرف باقي الحكاية!
"""

output = Path("output")
output.mkdir(exist_ok=True)
(output / "story.txt").write_text(story.strip(), encoding="utf-8")

print(story)
