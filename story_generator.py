def create_story():
    first, second = random.choice(characters)
    idea = random.choice(story_ideas)

    scenes = [
        scene.format(a=first, b=second)
        for scene in idea["scenes"]
    ]

    # كل مشهد في سطر واحد عشان ملف الفيديو يقرأه صح
    output_lines = [
        f"عنوان القصة: {idea['title']}",
        "",
    ]

    for index, scene in enumerate(scenes, start=1):
        output_lines.append(f"المشهد {index}:")
        output_lines.append(scene)
        output_lines.append("")

    output_lines.extend([
        "النهاية:",
        "إيه رأيك في اللي حصل؟",
    ])

    story = "\n".join(output_lines)

    output = Path("output")
    output.mkdir(parents=True, exist_ok=True)

    (output / "story.txt").write_text(
        story,
        encoding="utf-8",
    )

    print(story)
    print("\nتم إنشاء القصة بنجاح!")


if __name__ == "__main__":
    create_story()
